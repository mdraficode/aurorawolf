import { chromium } from 'playwright';
import { pathToFileURL, fileURLToPath } from 'node:url';
const URL = pathToFileURL(fileURLToPath(import.meta.url) + '/../../../index.html').href + '?autostart=1&seed=7777&quality=low';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader'] });
const pg = await b.newPage({ viewport: { width: 900, height: 520 } });
const errs=[]; pg.on('pageerror',e=>errs.push(e.message));
await pg.goto(URL,{waitUntil:'domcontentloaded',timeout:120000});
await pg.waitForFunction(()=>typeof state!=='undefined'&&state==='play'&&window.CAMP,null,{timeout:120000});
await pg.waitForTimeout(3000);
console.log('t0', await pg.evaluate(()=>({d:wolf.distance,fps:fpsShow,tSec,keys:JSON.stringify(keys),state})));
await pg.keyboard.down('KeyW');
await pg.waitForTimeout(4000);
console.log('after 4s W', await pg.evaluate(()=>({d:wolf.distance,speed:wolf.speed,tSec,fps:fpsShow,keys:JSON.stringify(keys),inp:JSON.stringify(input)})));
await pg.keyboard.up('KeyW');
await pg.waitForTimeout(500);
console.log('errs',errs.length,errs.slice(0,3));
await b.close();
