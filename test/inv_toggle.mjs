import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-gl=angle', '--use-angle=swiftshader'] });
const pg = await b.newPage({ viewport: { width: 800, height: 390 } });
const errs = []; pg.on('pageerror', e => errs.push(e.message));
await pg.goto('file:///home/user/index.html?autostart=1&seed=31337&quality=low', { timeout: 90000, waitUntil: 'domcontentloaded' });
await pg.waitForFunction(() => typeof state !== 'undefined' && state === 'play', null, { timeout: 90000 });
await pg.waitForTimeout(2000);
await pg.evaluate(() => document.body.classList.add('touch'));
await pg.waitForTimeout(300);
const isOpen = () => pg.evaluate(() => document.getElementById('invWrap').classList.contains('show'));
const out = {};
await pg.click('#invBtn', { timeout: 8000 });
await pg.waitForTimeout(400);
out.afterOpen = await isOpen();
await pg.click('#invBtn', { timeout: 8000 });   // REAL click — proves the button is hit-testable above the shade
await pg.waitForTimeout(400);
out.afterSecondPress = await isOpen();
await pg.click('#invBtn', { timeout: 8000 });
await pg.waitForTimeout(300);
await pg.evaluate(() => document.getElementById('invClose').click());
await pg.waitForTimeout(200);
out.closeX = await isOpen();
console.log('INV ' + JSON.stringify({ ...out, errs }));
await b.close();
